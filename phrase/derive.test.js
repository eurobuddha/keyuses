/* Golden-vector test for derive.js — run with:  node derive.test.js
   Vectors (derive.vectors.json) are generated by Minima's own Java classes via
   scanner/DeriveVectors.java (see its header), covering BOTH tree shapes:
   classic 64 keys/level and block-as-keyuses 128 keys/level. */
"use strict";

require("./wordlist.js");                       // sets global KeyUsesWordList
globalThis.sha3_256 = require("./sha3.js").sha3_256;   // before derive.js looks for it
const D = require("./derive.js");

const vectors = require("./derive.vectors.json").vectors;
let failed = 0;

for (const v of vectors) {
  const label = `index ${v.index} kpl ${v.keysPerLevel} (${v.anyphrase ? "anyphrase" : "bip39"})`;
  try {
    const seed = D.seedFromPhrase(v.phrase, v.anyphrase);
    check(label + " baseseed", "0x" + D._toHexUpper(seed), v.baseseed);
    const a = D.deriveAddress(seed, v.index, null, v.keysPerLevel);
    check(label + " publickey", a.publickey, v.publickey);
    check(label + " address", a.hex, v.address);
    check(label + " mx", a.mx, v.mx);
  } catch (e) {
    failed++;
    console.error(`FAIL ${label}: ${e.message}`);
  }
}

function check(what, got, want) {
  if (got !== want) throw new Error(`${what}\n  got  ${got}\n  want ${want}`);
}

if (failed) { console.error(`\n${failed} vector(s) FAILED`); process.exit(1); }
console.log(`OK — all ${vectors.length} vectors match (both tree shapes)`);
